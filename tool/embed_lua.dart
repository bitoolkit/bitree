import 'dart:io';

void main() {
  final toolDirectory = File.fromUri(Platform.script).parent;
  final root = toolDirectory.parent;
  final prelude = File('${root.path}/packages/bitree_lua/lua/prelude.lua')
      .readAsStringSync();
  final dkjson = File('${root.path}/packages/bitree_lua/lua/vendor/dkjson.lua')
      .readAsStringSync();
  final source =
      '''
local dkjson = (function()
$dkjson
end)()

$prelude''';
  const delimiter = 'BTLUA';
  if (source.contains(')$delimiter"')) {
    throw StateError('Lua source contains the raw string delimiter.');
  }
  final header =
      '''
// Generated by tool/embed_lua.dart. Do not edit.
inline constexpr char kPrelude[] = R"$delimiter(
$source
)$delimiter";
''';
  final output = File('${root.path}/packages/bitree_lua/native/prelude.inc');
  if (output.existsSync() && output.readAsStringSync() == header) return;
  output.writeAsStringSync(header);
}
